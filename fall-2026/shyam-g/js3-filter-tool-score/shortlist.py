"""Source-grounded shortlist (Chapter 7).

  python shortlist.py --claude     # ask Claude (claude -p, no tools) for a justification per kept posting
  python shortlist.py              # relabel using the saved Claude responses (no new calls)

For each kept posting: three gate claims computed from the posting fields, and Claude's claims.
Every claim gets a supported / contradicted / insufficient label from js3/evidence.py, plus the
abstention verdict. Writes reports/SHORTLIST.md and reports/shortlist.json.
Claude responses are saved verbatim, with a timestamp, in reports/claude/shortlist/<id>.json.
"""
from __future__ import annotations

import concurrent.futures as cf
import datetime
import json
import pathlib
import re
import sys

from js3.claude_cli import ask_claude
from js3.evidence import gate_claims, label_claim, verdict
from js3.filter import decide, load_corpus, load_rules

ROOT = pathlib.Path(__file__).resolve().parent
CDIR = ROOT / "reports" / "claude" / "shortlist"
MAX_CONTENT = 6000


def build_prompt(p: dict) -> str:
    t = (ROOT / "prompts" / "justify.txt").read_text(encoding="utf-8")
    return (t.replace("{{ID}}", p["id"]).replace("{{TITLE}}", p["title"])
             .replace("{{LOCATION}}", p["location"]).replace("{{CONTENT}}", p["content"][:MAX_CONTENT]))


def fetch(p: dict) -> None:
    started = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
    raw = ask_claude(build_prompt(p))
    CDIR.mkdir(parents=True, exist_ok=True)
    (CDIR / f"{p['id']}.json").write_text(json.dumps({
        "posting_id": p["id"], "asked_at": started, "via": "claude -p --tools '' (Claude Code CLI)",
        "prompt_file": "prompts/justify.txt", "raw_response": raw}, indent=1, ensure_ascii=False),
        encoding="utf-8")
    print("got", p["id"], p["title"])


def parse(raw: str):
    m = re.search(r"\{.*\}", raw, re.S)
    try:
        return json.loads(m.group(0))["claims"]
    except Exception:
        return None


def esc(s) -> str:
    return str(s or "").replace("|", "\\|").replace("\n", " ")


def main(use_claude: bool) -> None:
    rules = load_rules()
    kept = [p for p in load_corpus() if decide(p, rules)["decision"] == "keep"]
    if use_claude:
        with cf.ThreadPoolExecutor(4) as ex:
            list(ex.map(fetch, kept))
    rows = []
    for p in kept:
        g = gate_claims(p, rules)
        f = CDIR / f"{p['id']}.json"
        saved = json.loads(f.read_text(encoding="utf-8")) if f.exists() else None
        claims = parse(saved["raw_response"]) if saved else None
        labeled = [dict(c, **label_claim(p, c, rules)) for c in (claims or [])]
        rows.append({"id": p["id"], "title": p["title"], "location": p["location"], "url": p["url"],
                     "score": decide(p, rules)["score"], "gates": g, "verdict": verdict(g),
                     "claude_asked_at": saved["asked_at"] if saved else None,
                     "claude_parsed": claims is not None, "claims": labeled})
    (ROOT / "reports" / "shortlist.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False),
                                                     encoding="utf-8")
    write_md(rows, rules)


def write_md(rows, rules) -> None:
    L = [f"# Source-grounded shortlist (filter v{rules['version']})", "",
         "Generated by `python shortlist.py` from `reports/shortlist.json`. Gate claims are computed from the "
         "posting fields. Claude's claims come from real `claude -p` responses (timestamps below; raw text in "
         "`reports/claude/shortlist/`). **Every label in these tables is computed by `js3/evidence.py` against "
         "the posting's own text. None of them is my hand judgment.** My hand checks are in "
         "`reports/SHORTLIST-NOTES.md`.", "",
         "Boards covered: formlabs, spotify, palantir (corpus of 2026-11-10). `nosuchboard-js2-xyz`: "
         "**unchecked** (HTTP 404).", "",
         "## Summary", "",
         "| # | Title | Location | Score | Role | Location | Experience | Verdict (abstention rule) |",
         "|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        g = r["gates"]
        L.append(f"| {i} | {esc(r['title'])} | {esc(r['location'])} | {r['score']} | {g['role']['label']} | "
                 f"{g['location']['label']} | {g['experience']['label']} | **{r['verdict']['verdict']}** |")
    tot: dict = {}
    for r in rows:
        for c in r["claims"]:
            tot[c["label"]] = tot.get(c["label"], 0) + 1
    L += ["", f"Claude's claims across the shortlist, by computed label: {tot}", ""]
    for i, r in enumerate(rows, 1):
        L += [f"## {i}. {r['title']} ({r['location']})", f"<{r['url']}>, posting id {r['id']}", "",
              "| Claim | Source | Label | Why | Evidence (from the posting) |", "|---|---|---|---|---|"]
        for k, v in r["gates"].items():
            L.append(f"| {k} gate | computed | **{v['label']}** | {esc(v['why'])} | {esc(v['evidence'])[:160]} |")
        if not r["claude_parsed"]:
            L.append("| (Claude response missing or not parseable) | Claude | insufficient | | |")
        for c in r["claims"]:
            L.append(f"| {esc(c.get('claim'))} | Claude ({esc(c.get('type'))}) | **{c['label']}** | "
                     f"{esc(c['why'])} | {esc(c.get('quote'))[:160]} |")
        because = r["verdict"]["because"]
        line = f"Verdict: **{r['verdict']['verdict']}**"
        if because:
            line += f" (unsettled or contradicted: {', '.join(because)})"
        if r["claude_asked_at"]:
            line += f". Claude asked at {r['claude_asked_at']}."
        L += ["", line, ""]
    (ROOT / "reports" / "SHORTLIST.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote reports/SHORTLIST.md ({len(rows)} postings)")


if __name__ == "__main__":
    main("--claude" in sys.argv)
