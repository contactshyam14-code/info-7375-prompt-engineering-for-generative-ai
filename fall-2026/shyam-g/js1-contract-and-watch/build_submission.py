"""Concatenate every JS1 deliverable into one file: python build_submission.py -> JS1-SUBMISSION.md"""
import pathlib

ROOT = pathlib.Path(__file__).parent
PARTS = [
    ("README (language, toolchain, commands, what ran, sign-off, driver's seat)", "README.md", "md"),
    ("CONTRACT", "CONTRACT.md", "md"),
    ("Sampling report (Chapter 1)", "SAMPLING.md", "md"),
    ("Prompt experiment (Chapter 2)", "EXPERIMENT.md", "md"),
    ("Action-surface comparison (Chapter 3)", "ACTION-SURFACE.md", "md"),
    ("SOURCES", "SOURCES.md", "md"),
    ("FRICTIONAL", "FRICTIONAL.md", "md"),
    ("Evidence: red run before implementation", "evidence/00-red-run-before-implementation.txt", "text"),
    ("Evidence: seeded two runs", "evidence/01-seeded-two-runs.txt", "text"),
    ("Evidence: action-surface runs", "surface/runs.txt", "text"),
    ("Allow-list", "allowlist.txt", "text"),
    ("Persona (fictional)", "persona/jordan_rivera.json", "json"),
    ("Prompt contract (baseline)", "prompts/baseline.txt", "text"),
    ("Hand labels", "labels/hand_labels.csv", "csv"),
    ("Code: agent.py", "agent.py", "python"),
    ("Code: study.py", "study.py", "python"),
    ("Tests: test_contract.py (written before the code)", "tests/test_contract.py", "python"),
    ("Tests: test_extra.py", "tests/test_extra.py", "python"),
    ("Tests: test_resume.py", "tests/test_resume.py", "python"),
]

out = ["# JS1 — Contract and Watch: complete submission in one file",
       "", "Generated by `build_submission.py` from the files in this folder. Raw board responses and the",
       "state files are too large to inline; they are in `state/`, `state-seeded/` and `seeded/`.", ""]
out += ["## Contents"] + [f"{i}. {t}" for i, (t, _, _) in enumerate(PARTS, 1)] + [""]
for i, (title, path, kind) in enumerate(PARTS, 1):
    body = (ROOT / path).read_text(encoding="utf-8").strip()
    out += ["---", "", f"## {i}. {title}", f"_Source: `{path}`_", ""]
    if kind == "md":
        out += [line if not line.startswith("#") else "#" + line for line in body.splitlines()]
    else:
        out += [f"```{kind}", body, "```"]
    out.append("")
(ROOT / "JS1-SUBMISSION.md").write_text("\n".join(out), encoding="utf-8")
print("wrote JS1-SUBMISSION.md")
